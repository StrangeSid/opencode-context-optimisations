#!/usr/bin/env node
/**
 * A/B quality harness for the request lane.
 *
 * It compresses a synthetic transcript with the real LLMLingua sidecar, asks
 * the same fact questions over the original and compressed transcripts through
 * the OpenCode Go API, and reports per-fact retention and token usage.
 *
 * Prerequisites:
 *   1. A .env with OC_GO_KEY (gitignored).
 *   2. A running worker: python/llmlingua_worker.py --port 8765
 *
 * Usage:
 *   npm run eval:quality
 *   npm run eval:quality -- --runs 2 --model deepseek-v4.1-flash
 *   npm run eval:quality -- --json
 */

import { randomUUID } from "node:crypto"
import { existsSync, readFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { estimateTokens } from "../src/classify.ts"
import { createHttpCompressor } from "../src/compressor.ts"
import { createLruCache, optimizeTranscript } from "../src/optimizer.ts"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")

function loadEnv() {
  const file = resolve(ROOT, ".env")
  if (!existsSync(file)) return
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith("#")) continue
    const separator = trimmed.indexOf("=")
    if (separator < 0) continue
    const key = trimmed.slice(0, separator).trim()
    let value = trimmed.slice(separator + 1).trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    if (!(key in process.env)) process.env[key] = value
  }
}

function option(name, fallback) {
  const index = process.argv.indexOf("--" + name)
  if (index >= 0 && process.argv[index + 1]) return process.argv[index + 1]
  return fallback
}

function flag(name) {
  return process.argv.includes("--" + name)
}

function fail(message) {
  console.error("eval: " + message)
  process.exit(1)
}

loadEnv()

const apiKey = process.env.OC_GO_KEY
if (!apiKey) {
  fail("OC_GO_KEY is missing. Add it to .env (see .env.example).")
}

const model = option("model", process.env.OC_GO_MODEL || "deepseek-v4.1-flash")
const baseUrl = (process.env.OC_GO_BASE_URL || "https://opencode.ai/inference/go/v1").replace(/\/$/, "")
const endpoint = option(
  "endpoint",
  process.env.LLMLINGUA_ENDPOINT || "http://127.0.0.1:8765/compress",
)
const runs = Math.max(1, Number(option("runs", "1")) || 1)
const sessionId = "quality-eval-" + randomUUID()

const facts =
  "The retry limit is 7. The connection failed with ECONNREFUSED on 127.0.0.1:5433. " +
  "Do not modify src/legacy/parser.ts, which is frozen. The cache key uses SHA-256. " +
  "The migration must run after the index rebuild."

const filler =
  "I reviewed the build logs and compared the module resolution against the package exports map. " +
  "The same import resolves from a different root in the test package. " +
  "I cleared the dependency cache and reinstalled, but the error persisted. " +
  "Next I will inspect the compiled output and the package manifest again. "

const oldProse = facts + " " + filler.repeat(10)

const toolProse =
  "The read tool returned the package manifest and the relevant source files. " +
  "The exports map points at the compiled output, and the same module identifier resolves differently from the test package. " +
  "The test suite reported 182 passing tests, 3 skipped tests, and no failures. " +
  "I will compare both resolutions before changing the configuration. " +
  "The test suite reported 182 passing tests, 3 skipped tests, and no failures. " +
  "The compiled output is generated by the build step and should not be edited by hand. "

const code = [
  'import { readFile } from "node:fs/promises"',
  'import path from "node:path"',
  "",
  "export async function loadConfig(dir: string): Promise<Config> {",
  '  const file = path.join(dir, "config.json")',
  '  const raw = await readFile(file, "utf8")',
  "  return JSON.parse(raw)",
  "}",
].join("\n")

const errorText = "Error: ECONNREFUSED 127.0.0.1:5433"

function makeMessages(question) {
  return [
    {
      role: "assistant",
      content: [
        { type: "text", text: oldProse },
        { type: "text", text: code },
      ],
    },
    {
      role: "tool",
      content: [
        {
          type: "tool-result",
          id: "call-read",
          name: "read",
          result: { type: "text", value: toolProse },
        },
      ],
    },
    {
      role: "assistant",
      content: [
        {
          type: "tool-result",
          id: "call-bash",
          name: "bash",
          result: { type: "error", value: errorText },
        },
      ],
    },
    {
      role: "user",
      content: [{ type: "text", text: question }],
    },
  ]
}

function renderPart(part) {
  if (!part || typeof part !== "object") return ""
  if (part.type === "text" && typeof part.text === "string") return part.text
  if (part.type === "tool-call") {
    return "[tool-call " + (part.name || "unknown") + "] " + JSON.stringify(part.input)
  }
  if (part.type === "tool-result" && part.result) {
    const value = part.result.value
    return typeof value === "string" ? value : JSON.stringify(value)
  }
  return ""
}

function render(messages) {
  return messages
    .map((message) => {
      const content = typeof message.content === "string"
        ? message.content
        : (Array.isArray(message.content) ? message.content : []).map(renderPart).filter(Boolean).join("\n")
      return "[" + message.role + "]\n" + content
    })
    .join("\n\n")
}

const questions = [
  {
    id: "retry-port-file",
    text:
      "How many retries are allowed, what host and port failed, and which file must not be modified? " +
      "Answer with the three values only.",
    checks: [
      { name: "retry=7", pattern: "\\b7\\b|\\bseven\\b", flags: "i" },
      { name: "port=5433", pattern: "5433", flags: "" },
      { name: "frozen file", pattern: "src\\/legacy\\/parser\\.ts|legacy\\/parser|parser\\.ts", flags: "i" },
    ],
  },
  {
    id: "cache-migration",
    text:
      "Which hash algorithm is used for the cache key, and what must run after the index rebuild? " +
      "Answer in one short sentence.",
    checks: [
      { name: "SHA-256", pattern: "sha-?256", flags: "i" },
      { name: "migration after rebuild", pattern: "migration[^.]{0,80}index rebuild|index rebuild[^.]{0,80}migration", flags: "i" },
    ],
  },
  {
    id: "test-counts",
    text: "How many tests passed and how many were skipped? Answer with two numbers.",
    checks: [
      { name: "passed=182", pattern: "\\b182\\b", flags: "" },
      { name: "skipped=3", pattern: "\\b3\\b", flags: "" },
    ],
  },
]

async function checkWorker() {
  const health = new URL(endpoint)
  health.pathname = health.pathname.replace(/\/compress\/?$/, "/health")
  const response = await fetch(health, { signal: AbortSignal.timeout(10_000) })
  if (!response.ok) {
    fail("worker health check failed at " + health + " (HTTP " + response.status + ")")
  }
  const body = await response.json()
  if (!body || body.ready !== true) {
    fail("worker is not ready at " + health + "; start it with python/llmlingua_worker.py")
  }
  return health.toString()
}

async function ask(transcript, question) {
  const response = await fetch(baseUrl + "/chat/completions", {
    method: "POST",
    headers: {
      authorization: "Bearer " + apiKey,
      "content-type": "application/json",
      "x-opencode-session": sessionId,
    },
    body: JSON.stringify({
      model,
      messages: [
        {
          role: "system",
          content:
            "You are a precise coding-session assistant. Use only the transcript. " +
            "If a fact is absent, say it is absent. Answer concisely.",
        },
        {
          role: "user",
          content: "Transcript:\n" + transcript + "\n\nQuestion: " + question,
        },
      ],
      max_tokens: 800,
      temperature: 0,
    }),
    signal: AbortSignal.timeout(120_000),
  })

  if (!response.ok) {
    const detail = (await response.text()).slice(0, 400)
    throw new Error("OpenCode Go HTTP " + response.status + ": " + detail)
  }

  const data = await response.json()
  const content = data && data.choices && data.choices[0] && data.choices[0].message
    ? data.choices[0].message.content
    : undefined
  if (typeof content !== "string" || !content.trim()) {
    throw new Error("OpenCode Go returned an empty message")
  }
  return { content: content.trim(), usage: data.usage || null }
}

function score(answer, checks) {
  const passed = []
  const missing = []
  for (const check of checks) {
    const regex = new RegExp(check.pattern, check.flags)
    if (regex.test(answer)) passed.push(check.name)
    else missing.push(check.name)
  }
  return { passed, missing, ok: missing.length === 0 }
}

function costOf(usage) {
  if (!usage) return 0
  if (usage.opencode && typeof usage.opencode.list_cost === "number") {
    return usage.opencode.list_cost
  }
  return typeof usage.cost === "number" ? usage.cost : 0
}

async function main() {
  const healthUrl = await checkWorker()
  const backend = createHttpCompressor({ endpoint, timeoutMs: 10_000 })
  const cache = createLruCache(200)
  const results = []
  let apiCost = 0

  for (let run = 0; run < runs; run += 1) {
    for (const question of questions) {
      const messages = makeMessages(question.text)
      const compressed = JSON.parse(JSON.stringify(messages))
      const stats = await optimizeTranscript(
        compressed,
        {
          minTokens: 100,
          budgetTokens: 8000,
          protectedTurns: 2,
          rate: 0.6,
          timeoutMs: 10_000,
          validateLiterals: false,
        },
        { backend, cache },
      )

      const originalText = render(messages)
      const compressedText = render(compressed)
      const original = await ask(originalText, question.text)
      const after = await ask(compressedText, question.text)
      apiCost += costOf(original.usage) + costOf(after.usage)

      const originalScore = score(original.content, question.checks)
      const compressedScore = score(after.content, question.checks)
      results.push({
        run: run + 1,
        question: question.id,
        original: {
          estimatedTokens: estimateTokens(originalText),
          promptTokens: original.usage ? original.usage.prompt_tokens : null,
          answer: original.content,
          facts: originalScore,
        },
        compressed: {
          estimatedTokens: estimateTokens(compressedText),
          promptTokens: after.usage ? after.usage.prompt_tokens : null,
          answer: after.content,
          facts: compressedScore,
          stats,
        },
      })
    }
  }

  const originalPasses = results.filter((result) => result.original.facts.ok).length
  const compressedPasses = results.filter((result) => result.compressed.facts.ok).length
  const total = results.length
  const originalTokens = results.reduce((sum, result) => sum + result.original.estimatedTokens, 0)
  const compressedTokens = results.reduce(
    (sum, result) => sum + result.compressed.estimatedTokens,
    0,
  )
  const summary = {
    model,
    endpoint,
    health: healthUrl,
    runs,
    total,
    originalPasses,
    compressedPasses,
    originalEstimatedTokens: originalTokens,
    compressedEstimatedTokens: compressedTokens,
    tokenReduction:
      originalTokens > 0
        ? Math.round((1 - compressedTokens / originalTokens) * 1000) / 10
        : 0,
    apiCostUsd: Math.round(apiCost * 1_000_000) / 1_000_000,
    strictFailure: compressedPasses < originalPasses,
  }

  if (flag("json")) {
    console.log(JSON.stringify({ summary, results }, null, 2))
  } else {
    console.log("OpenCode Go quality eval")
    console.log("model: " + model)
    console.log("worker: " + healthUrl)
    console.log("runs: " + runs + " | questions: " + questions.length)
    console.log("")
    for (const result of results) {
      const originalTotal =
        result.original.facts.passed.length + result.original.facts.missing.length
      const compressedTotal =
        result.compressed.facts.passed.length + result.compressed.facts.missing.length
      console.log(
        "run " + result.run + " | " + result.question +
          " | original " + result.original.facts.passed.length + "/" + originalTotal +
          " | compressed " + result.compressed.facts.passed.length + "/" + compressedTotal,
      )
      if (result.compressed.facts.missing.length > 0) {
        console.log("  compressed answer: " + result.compressed.answer)
      }
    }
    console.log("")
    console.log(
      "summary: original " + originalPasses + "/" + total +
        " | compressed " + compressedPasses + "/" + total +
        " | estimated tokens " + originalTokens + " -> " + compressedTokens +
        " (" + summary.tokenReduction + "% smaller)" +
        " | API cost $" + summary.apiCostUsd,
    )
  }

  if (flag("strict") && summary.strictFailure) {
    process.exitCode = 1
  }
}

main().catch((error) => {
  console.error("eval failed: " + (error instanceof Error ? error.message : String(error)))
  process.exit(1)
})
